#!/usr/bin/env python
"""
upload_model.py

PC-side helper to push model_coeffs.json to the ESP32 over a serial port.

Usage examples:
  # Dry-run, print payload
  python upload_model.py --dry-run

  # Send to COM3 at 115200 and print device reply
  python upload_model.py --port COM3 --baud 115200 --wait-response

This script requires pyserial: pip install pyserial
"""
import argparse
import json
import sys
import time

try:
    import serial
    from serial.tools import list_ports
except (ImportError, ModuleNotFoundError):
    serial = None


def build_payload(data):
    # Build a single-line JSON payload with the polynomial coefficients and metadata
    # Expected data format from model_coeffs.json generated by train_model.py
    
    coef_array = data.get("coefficients", [])
    
    # Handle both new format (with 14 polynomial coefficients) and old format
    if len(coef_array) == 14:
        # New format: polynomial coefficients
        payload = {
            "coef_poly": coef_array,
            "intercept_c": data.get("intercept", 0),
            "scaler_mean": data.get("scaler_mean"),
            "scaler_scale": data.get("scaler_scale"),
            "r2": data.get("performance", {}).get("r2", 0),
            "rmse": data.get("performance", {}).get("rmse", 0),
            "mae": data.get("performance", {}).get("mae", 0),
            "model": data.get("model", "ridge_poly2")
        }
    else:
        # Fallback for old format or custom coefficients
        payload = {
            "coef_a": data.get("coef_a", data.get("coef_nir", 0)),
            "coef_b": data.get("coef_b", data.get("coef_nir", 0)),
            "intercept_c": data.get("intercept_c", data.get("intercept", 0)),
            "scale": data.get("scale", 100000),
            "r2": data.get("performance", {}).get("r2", 0) if isinstance(data.get("performance"), dict) else data.get("r2", 0),
            "rmse": data.get("performance", {}).get("rmse", 0) if isinstance(data.get("performance"), dict) else data.get("rmse", 0)
        }
    
    return json.dumps(payload, separators=(',', ':')) + "\n"


def list_serial_ports():
    if serial is None:
        return []
    return [p.device for p in list_ports.comports()]


def main():
    p = argparse.ArgumentParser(description="Upload model_coeffs.json to ESP32 over serial")
    p.add_argument('--file', '-f', default='model_coeffs.json', help='Path to model_coeffs.json')
    p.add_argument('--port', help='Serial port (e.g., COM3). If omitted script will list ports and exit.')
    p.add_argument('--baud', type=int, default=115200, help='Baud rate')
    p.add_argument('--timeout', type=float, default=2.0, help='Read timeout (seconds)')
    p.add_argument('--wait-response', action='store_true', help='Wait and print device response after sending')
    p.add_argument('--dry-run', action='store_true', help='Do not open serial port; just print payload')
    args = p.parse_args()

    try:
        with open(args.file, 'r', encoding='utf-8') as fh:
            data = json.load(fh)
    except (FileNotFoundError, json.JSONDecodeError) as e:
        print('Failed to open or parse', args.file, e)
        sys.exit(2)

    payload = build_payload(data)

    if args.dry_run:
        print('DRY RUN - payload to send:')
        print(payload)
        return

    if args.port is None:
        print('No port specified. Available ports:')
        for pport in list_serial_ports():
            print('  ', pport)
        print('Run with --port COMx to send payload')
        return

    if serial is None:
        print('pyserial is required. Install with: pip install pyserial')
        sys.exit(2)

    print(f'Sending to {args.port} at {args.baud}...')
    try:
        ser = serial.Serial(args.port, args.baud, timeout=args.timeout)
    except (OSError, serial.SerialException) as e:
        print('Failed to open serial port:', e)
        sys.exit(3)

    # flush input/output briefly
    time.sleep(0.1)
    ser.reset_input_buffer()
    ser.reset_output_buffer()

    ser.write(payload.encode())
    ser.flush()
    print('Payload sent.')

    if args.wait_response:
        # give device a small time to reply
        time.sleep(0.2)
        out = b''
        # read what's available
        while True:
            chunk = ser.read(1024)
            if not chunk:
                break
            out += chunk
        try:
            print('Device reply:\n', out.decode(errors='ignore'))
        except Exception:
            print('Device reply (raw):', out)

    ser.close()


if __name__ == '__main__':
    main()
